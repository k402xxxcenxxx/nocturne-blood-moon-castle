let current = 'en';
export function detectLanguage(preferred = '') { return /^zh/i.test(preferred) ? 'zh-Hant' : 'en'; }
export function setLanguage(lang) { current = STRINGS[lang] ? lang : 'en'; return current; }
export function language() { return current; }
export function t(key, vars = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
